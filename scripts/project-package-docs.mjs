function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

function posix(value) {
  return value.replaceAll('\\', '/');
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

async function exists(file) {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
}

async function walk(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = posix(path.join(prefix, entry.name));
    if (entry.isDirectory()) files.push(...await walk(path.join(directory, entry.name), relative));
    else if (entry.isFile()) files.push(relative);
  }
  return files.sort();
}

async function readJson(file) {
  return JSON.parse(await readFile(file, 'utf8'));
}

function option(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) return undefined;
  invariant(process.argv[index + 1] && !process.argv[index + 1].startsWith('--'), `${name} requires a path.`);
  return process.argv[index + 1];
}

async function resolveUpstream(value) {
  let candidate = path.resolve(root, value);
  if (await exists(path.join(candidate, 'docs', 'manifest.json'))) candidate = path.join(candidate, 'docs');
  invariant(await exists(path.join(candidate, 'manifest.json')), `Upstream Core docs manifest is missing: ${candidate}`);
  invariant(path.resolve(candidate) !== path.resolve(outputRoot), 'The generated Robotics bundle cannot be its own upstream.');
  return candidate;
}

async function refreshSnapshot(upstreamRoot) {
  const source = await resolveUpstream(upstreamRoot);
  const next = path.join(root, '.lds-docs-upstream', 'core.next');
  invariant(next.startsWith(path.join(root, '.lds-docs-upstream') + path.sep), 'Unsafe snapshot target.');
  await rm(next, { recursive: true, force: true });
  await mkdir(path.dirname(next), { recursive: true });
  await cp(source, next, { recursive: true, force: true });
  await rm(snapshotRoot, { recursive: true, force: true });
  await cp(next, snapshotRoot, { recursive: true, force: true });
  await rm(next, { recursive: true, force: true });
}

function parsePublicExports(source) {
  const entries = [];
  for (const match of source.matchAll(/export\s*\{([\s\S]*?)\}\s*from\s*['"]\.\/([^'"]+)['"]/g)) {
    for (const item of match[1].split(',')) {
      const normalized = item.replace(/\/\*[\s\S]*?\*\//g, '').trim();
      if (!normalized || normalized.startsWith('type ')) continue;
      const parts = normalized.split(/\s+as\s+/);
      entries.push({ name: parts.at(-1).trim(), source: `src/${match[2].replace(/\.(?:js|jsx|ts|tsx)$/, '')}` });
    }
  }
  return entries;
}

function cssTokenData(source, relative) {
  const definitions = [...source.matchAll(/(?<![A-Za-z0-9-])(--[A-Za-z0-9-]+)\s*:/g)].map((match) => match[1]);
  const references = [...source.matchAll(/var\(\s*(--[A-Za-z0-9-]+)/g)].map((match) => match[1]);
  return {
    path: relative,
    sha256: sha256(source),
    definitions: [...new Set(definitions)].sort(),
    references: [...new Set(references)].sort(),
  };
}

function indentHeadings(markdown) {
  return markdown.replace(/^(#{1,5}) /gm, '#$1 ');
}

function routeSnapshotLinks(markdown) {
  return markdown.replace(/\]\(([^)]+)\)/g, (whole, target) => {
    if (/^(?:[a-z]+:|#|\/)/i.test(target)) return whole;
    const [file, suffix = ''] = target.split(/(?=[?#])/u, 2);
    const normalized = path.posix.normalize(file.replace(/^\.\//, ''));
    invariant(!normalized.startsWith('../'), `Upstream Markdown link escapes its docs bundle: ${target}`);
    return `](./shared/${normalized}${suffix})`;
  });
}

function renderDomainIndex() {
  const rows = domainDocuments.map((file) => (
    `| [${path.basename(file)}](./${path.basename(file)}) | Robotics-authored domain contract |`
  )).join('\n');
  return `${generatedMarker}
# LDS Robotics domain documentation

These files are Robotics-authored deltas layered on the pinned shared LDS
adoption and Foundation snapshot. Shared policy remains under \`../shared/\`.

| Document | Role |
| --- | --- |
${rows}
`;
}

function projectDomainDocument(relative, source) {
  let projected = source;
  if (relative === 'docs/ROBOTICS_UI_ADOPTION.md') projected = projected.replaceAll('](package/)', '](../)');
  if (relative === 'docs/references/ATTRIBUTIONS.md') {
    projected = projected
      .replaceAll('](../../LICENSE)', '](../licenses/LICENSE)')
      .replaceAll('](../../THIRD_PARTY_NOTICES.md)', '](../licenses/THIRD_PARTY_NOTICES.md)')
      .replaceAll('](../../licenses/MIT-WDS.txt)', '](../licenses/MIT-WDS.txt)')
      .replaceAll('](../../licenses/PRETENDARD-OFL-1.1.txt)', '](../licenses/PRETENDARD-OFL-1.1.txt)');
  }
  return projected;
}

