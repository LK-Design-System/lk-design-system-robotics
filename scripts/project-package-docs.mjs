async function buildTokenManifest(packageManifest) {
  const sources = [];
  for (const relative of ['tokens/components.css', 'tokens/focus.css']) {
    sources.push(cssTokenData(await readFile(path.join(root, relative), 'utf8'), relative));
  }
  return {
    schemaVersion: 1,
    kind: 'lds-robotics-token-manifest',
    package: { name: packageManifest.name, version: packageManifest.version },
    sources,
  };
}

async function buildDomainRegistry(packageManifest) {
  const indexSource = await readFile(path.join(root, 'src', 'index.js'), 'utf8');
  const publicExports = parsePublicExports(indexSource);
  const publicNames = new Set(publicExports.map(({ name }) => name));
  const glyphs = [];
  for (const definition of glyphDefinitions) {
    const source = await readFile(path.join(root, definition.source), 'utf8');
    for (const name of definition.definitions) {
      invariant(new RegExp(`export\\s+(?:const|function)\\s+${name}\\b`).test(source), `${definition.source} no longer exports ${name}.`);
    }
    for (const [name] of definition.publicBindings) invariant(publicNames.has(name), `Missing public glyph binding ${name}.`);
    glyphs.push({
      id: definition.id,
      source: {
        repositoryPath: definition.source,
        sha256: sha256(source),
      },
      definitions: definition.definitions,
      publicBindings: definition.publicBindings.map(([name, sourcePath]) => ({
        package: packageManifest.name,
        export: name,
        source: sourcePath,
      })),
      storyId: definition.storyId,
    });
  }
  return {
    schemaVersion: 1,
    kind: 'lds-robotics-domain-symbol-registry',
    package: { name: packageManifest.name, version: packageManifest.version },
    glyphs,
    publicConstants: publicExports.filter(({ name }) => /^[A-Z][A-Z0-9_]+$/.test(name)).map((entry) => ({
      ...entry,
      package: packageManifest.name,
    })),
  };
}

function json(value) {
  return Buffer.from(`${JSON.stringify(value, null, 2)}\n`);
}

function projectChecklist(source) {
  const checklist = structuredClone(source);
  const rewrite = (reference) => (
    reference.startsWith('./') ? `./shared/${reference.slice(2)}` : reference
  );
  for (const facet of checklist.facets) facet.references = facet.references.map(rewrite);
  checklist.componentMapping.references = checklist.componentMapping.references.map(rewrite);
  checklist.$schema = './LDS_UI_ADOPTION_CONTRACT.schema.json';
  return checklist;
}

async function buildOutputs() {
  invariant(await exists(path.join(snapshotRoot, 'manifest.json')), 'Committed Core docs snapshot is missing. Run with --upstream-root <core-docs>.');
  const [packageManifest, upstreamManifest, upstreamFiles] = await Promise.all([
    readJson(packageManifestPath),
    readJson(path.join(snapshotRoot, 'manifest.json')),
    walk(snapshotRoot),
  ]);
  const roboticsRefStatus = packageManifest.lds?.refStatus ?? 'release-candidate';
  invariant(upstreamManifest.kind === 'lds-package-documentation', 'Invalid upstream documentation manifest kind.');
  invariant(upstreamManifest.package?.name === '@lk-design-system/lds-core', 'Upstream snapshot must be LDS Core docs.');

  const outputs = new Map();
  for (const relative of upstreamFiles) {
    outputs.set(`shared/${relative}`, await readFile(path.join(snapshotRoot, relative)));
  }
  const upstreamChecklist = await readJson(path.join(snapshotRoot, 'adoption-checklist.json'));
  outputs.set('adoption-checklist.json', json(projectChecklist(upstreamChecklist)));
  for (const relative of [
    'LDS_UI_ADOPTION_CONTRACT.schema.json',
    'adoption-report.schema.json',
    'adoption-report.example.json',
    'adoption-config.schema.json',
  ]) outputs.set(relative, await readFile(path.join(snapshotRoot, relative)));
  outputs.set('adoption-workflow.md', Buffer.from(renderWorkflow(
    await readFile(path.join(snapshotRoot, 'adoption-workflow.md'), 'utf8'),
    upstreamManifest,
    upstreamChecklist.invariant,
  )));
  outputs.set('llms.txt', Buffer.from(renderLlms(
    await readFile(path.join(snapshotRoot, 'llms.txt'), 'utf8'),
    upstreamManifest,
  )));
  outputs.set('tokens/manifest.json', json(await buildTokenManifest(packageManifest)));
  outputs.set('domain-symbol-registry.json', json(await buildDomainRegistry(packageManifest)));
  for (const relative of domainDocuments) {
    const source = await readFile(path.join(root, relative), 'utf8');
    outputs.set(`domain/${path.basename(relative)}`, Buffer.from(projectDomainDocument(relative, source)));
  }
  outputs.set('domain/README.md', Buffer.from(renderDomainIndex()));
  for (const [sourcePath, targetPath] of licenseDocuments) {
    const source = await readFile(path.join(root, sourcePath));
    outputs.set(
      targetPath,
      sourcePath === 'THIRD_PARTY_NOTICES.md'
        ? Buffer.from(source.toString('utf8').replaceAll('](licenses/', ']('))
        : source,
    );
  }

  const snapshotFiles = await Promise.all(upstreamFiles.map(async (relative) => ({
    path: relative,
    sha256: sha256(await readFile(path.join(snapshotRoot, relative))),
  })));
  const snapshot = {
    schemaVersion: 1,
    kind: 'lds-upstream-documentation-snapshot',
    package: upstreamManifest.package,
    source: upstreamManifest.source,
    manifestSha256: sha256(await readFile(path.join(snapshotRoot, 'manifest.json'))),
    files: snapshotFiles,
    projectedFiles: [...outputs.keys()].sort(),
  };
  outputs.set('upstream-snapshot.json', json(snapshot));

  const domainRecords = await Promise.all(domainDocuments.map(async (relative) => {
    const source = await readFile(path.join(root, relative));
    return {
      path: `domain/${path.basename(relative)}`,
      sourcePath: relative,
      sourceSha256: sha256(source),
      sha256: sha256(outputs.get(`domain/${path.basename(relative)}`)),
    };
  }));
  const canonicalRecord = upstreamManifest.source.documents.find(({ path: sourcePath }) => (
    sourcePath === 'docs/references/adoption/LDS_UI_ADOPTION_CONTRACT.json'
  ));
  invariant(canonicalRecord, 'Upstream manifest omits the canonical adoption contract source.');
  const contract = JSON.parse(outputs.get('adoption-checklist.json').toString('utf8'));
  const generatedRecords = [...outputs.entries()]
    .map(([relative, contents]) => ({ path: relative, sha256: sha256(contents) }))
    .sort((left, right) => left.path.localeCompare(right.path));
  const publicRoot = 'https://lk-design-system.github.io/lk-design-system-robotics/';
  const manifest = {
    schemaVersion: 1,
    kind: 'lds-package-documentation',
    package: { name: packageManifest.name, version: packageManifest.version, layer: 'robotics' },
    adoption: {
      contractKind: contract.kind,
      contractVersion: contract.contractVersion,
      invariant: contract.invariant,
      facetIds: contract.facets.map(({ id }) => id),
      componentMappingRequired: contract.completion.requiresComponentMapping,
      verdicts: contract.verdicts,
    },
    entrypoints: {
      llms: './llms.txt',
      adoptionChecklist: './adoption-checklist.json',
      adoptionReportSchema: './adoption-report.schema.json',
      adoptionReportExample: './adoption-report.example.json',
      adoptionConfigSchema: './adoption-config.schema.json',
      adoptionWorkflow: './adoption-workflow.md',
      domainIndex: './domain/README.md',
      tokenManifest: './tokens/manifest.json',
      domainSymbolRegistry: './domain-symbol-registry.json',
    },
    foundations: upstreamManifest.foundations,
    patterns: [...new Set([...(upstreamManifest.patterns ?? []), 'robotics-navigation', 'robotics-map', 'robotics-state'])],
    domain: { documents: domainRecords, foundationStories },
    publicDocs: {
      storybook: `${publicRoot}?path=/docs/lds-robotics-foundation-viewer-tokens--docs`,
      llms: `${publicRoot}llms.txt`,
      designSystem: `${publicRoot}design-system.json`,
      adoptionChecklist: `${publicRoot}adoption-checklist.json`,
      adoptionReportSchema: `${publicRoot}adoption-report.schema.json`,
      adoptionReportExample: `${publicRoot}adoption-report.example.json`,
      adoptionWorkflow: `${publicRoot}adoption-workflow.md`,
    },
    source: {
      robotics: {
        repository: 'LK-Design-System/lk-design-system-robotics',
        ref: `v${packageManifest.version}`,
        refStatus: roboticsRefStatus,
      },
      canonicalAdoption: {
        kind: contract.kind,
        version: contract.contractVersion,
        source: {
          repository: upstreamManifest.source.repository,
          ref: upstreamManifest.source.ref,
          refStatus: 'release-candidate',
          path: canonicalRecord.path,
          sha256: canonicalRecord.sha256,
        },
        snapshotManifestSha256: snapshot.manifestSha256,
      },
    },
    resources: {
      tokens: { path: './tokens/manifest.json', sha256: sha256(outputs.get('tokens/manifest.json')) },
      domainSymbols: { path: './domain-symbol-registry.json', sha256: sha256(outputs.get('domain-symbol-registry.json')) },
    },
    documents: generatedRecords,
  };
  outputs.set('manifest.json', json(manifest));
  return outputs;
}

async function applyOutputs(outputs, check) {
  const previous = await exists(path.join(outputRoot, 'upstream-snapshot.json'))
    ? (await readJson(path.join(outputRoot, 'upstream-snapshot.json'))).projectedFiles ?? []
    : [];
  const expected = new Set(outputs.keys());
  if (check) {
    const drift = [];
    for (const [relative, contents] of outputs) {
      const file = path.join(outputRoot, relative);
      if (!await exists(file) || !(await readFile(file)).equals(contents)) drift.push(relative);
    }
    for (const relative of previous) if (!expected.has(relative) && await exists(path.join(outputRoot, relative))) drift.push(relative);
    invariant(drift.length === 0, `Generated package docs drift: ${[...new Set(drift)].sort().join(', ')}`);
    console.log(`Validated deterministic Robotics documentation projection (${outputs.size} files).`);
    return;
  }
  await mkdir(outputRoot, { recursive: true });
  for (const relative of previous) {
    if (!expected.has(relative)) await rm(path.join(outputRoot, relative), { force: true });
  }
  for (const [relative, contents] of outputs) {
    const target = path.join(outputRoot, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, contents);
  }
  console.log(`Projected ${outputs.size} Robotics package documentation files from the committed Core snapshot.`);
}

const check = process.argv.includes('--check');
const upstreamRoot = option('--upstream-root');
invariant(!(check && upstreamRoot), '--check is read-only and cannot refresh --upstream-root.');
if (upstreamRoot) await refreshSnapshot(upstreamRoot);
await applyOutputs(await buildOutputs(), check);
